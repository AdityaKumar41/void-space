export function translate(
  language: LanguageCode,
  message: string,
  values?: Record<string, string | number>,
): string {
  const translated = language === 'en' ? message : (messages[language][message] ?? message);
  return values
    ? Object.entries(values).reduce(
        (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
        translated,
      )
    : translated;
}

interface LanguageContextValue {
  readonly language: LanguageCode;
  setLanguage(language: LanguageCode): Promise<void>;
  t(message: string, values?: Record<string, string | number>): string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const { session, setPreferredLanguage } = useSession();
  const language = session?.user.preferredLanguage ?? 'en';

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage: setPreferredLanguage,
        t: (message, values) => translate(language, message, values),
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside <LanguageProvider>');
  return context;
}

export function useOptionalLanguage(): Pick<LanguageContextValue, 'language' | 't'> {
  const context = useContext(LanguageContext);
  return context ?? { language: 'en', t: (message: string) => message };
}
